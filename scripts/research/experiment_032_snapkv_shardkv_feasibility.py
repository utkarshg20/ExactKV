_FORBIDDEN_FIELDS = frozenset({
    "tokens_per_second",
    "throughput",
    "latency",
    "speedup",
    "runtime_seconds",
    "active_gpu_kv_bytes",
})


def _assert_no_forbidden_fields(obj: object, path: str = "artifact") -> None:
    if isinstance(obj, dict):
        hits = _FORBIDDEN_FIELDS & obj.keys()
        if hits:
            raise ValueError(f"Forbidden fields {hits} in {path}")
        for k, v in obj.items():
            _assert_no_forbidden_fields(v, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, item in enumerate(obj):
            _assert_no_forbidden_fields(item, f"{path}[{i}]")


def _class_label(cls: FeasibilityClass) -> str:
    return {
        FeasibilityClass.A_FEASIBLE_NOW: "**A — feasible now**",
        FeasibilityClass.B_RESTRICTED: "**B — restricted feasibility**",
        FeasibilityClass.C_NO_GO: "**C — no-go for now**",
    }[cls]


def _repo_inspection() -> dict[str, object]:
    """Lightweight local repository inspection for the feasibility memo."""
    from exactkv.compressors import list_compressors
    from exactkv.compressors.kvpress_knorm import create_kvpress_knorm_adapter

    has_kvpress_factory = callable(create_kvpress_knorm_adapter)
    registry = list_compressors()
    snapkv_in_registry = any("snapkv" in n for n in registry)
    shardkv_in_registry = any("shard" in n for n in registry)

    return {
        "default_registry_compressors": registry,
        "snapkv_in_default_registry": snapkv_in_registry,
        "shardkv_in_default_registry": shardkv_in_registry,
        "kvpress_knorm_factory_present": has_kvpress_factory,
        "backend_adapter_module": "exactkv/compressors/backend_adapter.py",
        "token_dropping_precedent": "exactkv/compressors/kvpress_knorm.py (Exp 005)",
        "exactkv_generator_recompress": (
            "exactkv/runtime/exactkv_generator.py — update_after_commit recompresses "
            "from full state each round (unchanged)."
        ),
        "verification_authoritative": (
            "exactkv/verification/engine.py — full KV verify only; no compressor hooks."
        ),
    }


