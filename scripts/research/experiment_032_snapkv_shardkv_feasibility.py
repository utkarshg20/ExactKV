def main() -> int:
    parser = argparse.ArgumentParser(description="Experiment 032 SnapKV/ShardKV feasibility")
    parser.add_argument(
        "--report-json",
        default=str(_ROOT / "reports" / "experiment_032_snapkv_shardkv_feasibility.json"),
    )
    parser.add_argument(
        "--report-md",
        default=str(_ROOT / "docs" / "EXPERIMENT_032_SNAPKV_SHARDKV_FEASIBILITY.md"),
    )
    args = parser.parse_args()

    artifact = build_feasibility_artifact()
    artifact["generated_at"] = datetime.now(timezone.utc).isoformat()
    artifact["repo_inspection"] = _repo_inspection()
    artifact["diagnostic_disclaimer"] = {
        "feasibility_study_only": True,
        "not_production_adapter_claim": True,
        "full_kv_verifier_authoritative": True,
        "no_speed_claim": True,
        "no_throughput_claim": True,
        "no_latency_claim": True,
        "no_runtime_improvement_claim": True,
        "no_tokens_per_second_claim": True,
        "no_active_gpu_memory_savings_claim": True,
        "no_production_serving_claim": True,
        "no_model_accuracy_improvement_claim": True,
        "production_snapkv_claim_allowed": False,
    }

    _assert_no_forbidden_fields(artifact)

    json_path = Path(args.report_json)
    md_path = Path(args.report_md)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(artifact, indent=2), encoding="utf-8")
    write_markdown(artifact, md_path)

    interp = artifact["interpretation"]
    print(
        f"Done: snapkv={interp['snapkv_classification']} "
        f"shardkv={interp['shardkv_classification']} "
        f"chosen={artifact['chosen_path']} "
        f"adapter_implemented={artifact['adapter_implemented']}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
