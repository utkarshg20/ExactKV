def main() -> int:
    parser = argparse.ArgumentParser(description="Exp 032 addendum Shard/SpectralQuant")
    parser.add_argument(
        "--report-json",
        default=str(_ROOT / "reports" / "experiment_032_addendum_shard_spectralquant.json"),
    )
    parser.add_argument(
        "--report-md",
        default=str(_ROOT / "docs" / "EXPERIMENT_032_ADDENDUM_SHARD_SPECTRALQUANT.md"),
    )
    args = parser.parse_args()

    artifact = build_addendum_artifact()
    artifact["generated_at"] = datetime.now(timezone.utc).isoformat()
    artifact["diagnostic_disclaimer"] = {
        "feasibility_addendum_only": True,
        "not_adapter_implementation": True,
        "external_results_not_exactkv": True,
        "full_kv_verifier_authoritative": True,
        "no_speed_claim": True,
        "no_throughput_claim": True,
        "no_active_gpu_memory_savings_claim": True,
        "no_production_serving_claim": True,
        "no_model_accuracy_improvement_claim": True,
    }

    _assert_no_forbidden_fields(artifact)

    json_path = Path(args.report_json)
    md_path = Path(args.report_md)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(artifact, indent=2), encoding="utf-8")
    write_markdown(artifact, md_path)

    interp = artifact["interpretation"]
    print(
        f"Done: snapkv={interp['snapkv_classification']} "
        f"shard={interp['shard_classification']} "
        f"spectralquant={interp['spectralquant_classification']} "
        f"phase5b={interp['phase5b_primary']} "
        f"preempt={artifact['shard_or_spectralquant_preempt_snapkv']}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
