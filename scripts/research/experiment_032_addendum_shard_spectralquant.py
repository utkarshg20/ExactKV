_FORBIDDEN_FIELDS = frozenset({
    "tokens_per_second",
    "throughput",
    "latency",
    "speedup",
    "runtime_seconds",
    "active_gpu_kv_bytes",
})


def _assert_no_forbidden_fields(obj: object, path: str = "artifact") -> None:
    if isinstance(obj, dict):
        hits = _FORBIDDEN_FIELDS & obj.keys()
        if hits:
            raise ValueError(f"Forbidden fields {hits} in {path}")
        for k, v in obj.items():
            _assert_no_forbidden_fields(v, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, item in enumerate(obj):
            _assert_no_forbidden_fields(item, f"{path}[{i}]")


def _class_label(cls: FeasibilityClass) -> str:
    return {
        FeasibilityClass.A_FEASIBLE_NOW: "**A — feasible now**",
        FeasibilityClass.B_RESTRICTED: "**B — restricted feasibility**",
        FeasibilityClass.C_NO_GO: "**C — no-go for now**",
    }[cls]


def _integration_table(notes: dict[str, str]) -> list[str]:
    labels = {
        "A_direct_kvcompressor": "A. direct KVCompressor backend",
        "B_external_drafter": "B. external drafter",
        "B_offline_calibration_tensor_compressor": "B. offline calibration + tensor compressor",
        "C_llama_sidecar_probe": "C. Llama-only sidecar/probe",
        "D_no_go": "D. no-go",
    }
    lines = ["", "| Path | Assessment |", "|---|---|"]
    for key, label in labels.items():
        if key in notes:
            lines.append(f"| {label} | {notes[key]} |")
    return lines


